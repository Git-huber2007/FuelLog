/** At least a year of lines: FuelLog's own, with the real quotes spread evenly between them. */
export const LINES: { text: string; by?: string }[] = OWN.flatMap((text, i) => {
  const q = Math.floor(((i + 1) * QUOTES.length) / OWN.length);
  return q > Math.floor((i * QUOTES.length) / OWN.length) ? [{ text }, QUOTES[q - 1]] : [{ text }];
});

/** One line per calendar day: the same all day, the next one tomorrow. */
export function DailyLine({ date }: { date: string }) {
  const { text, by } = LINES[Math.floor(Date.parse(`${date}T00:00Z`) / 86_400_000) % LINES.length];
  return (
    <p className="px-1 text-sm text-muted">
      {by ? <>&ldquo;{text}&rdquo; <span className="whitespace-nowrap font-semibold text-text">— {by}</span></> : text}
    </p>
  );
}
